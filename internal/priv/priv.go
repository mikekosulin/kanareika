// Package priv: every command that needs root, in one registry (ops_gen.go).
//
// Checks never write `sudo ...` themselves; they call Cmd(host, op, args...). How the op runs depends on the host's
// privilege mode:
//
//	none    run as is (the SSH user is root, or partial data is accepted)
//	sudo    `sudo -n sh -c '<snippet>'` — needs broad passwordless sudo
//	helper  `sudo -n /usr/local/libexec/kanareika-collect <op> [args]` — the only thing sudoers allows; the helper is
//	        generated from this same registry (RenderHelper) and validates every argument
//
// So the helper on the servers and the scanner can't drift apart: `kanareika helper` regenerates the script.
package priv

import (
	"fmt"
	"regexp"
	"strings"
)

const HelperPath = "/usr/local/libexec/kanareika-collect"

// Validator of one argument: "re" — an ERE matched against the whole argument; "enum" — one of the values.
type Validator struct {
	Kind string
	Rule string
	Enum []string
}

type Op struct {
	Snippet string
	Args    []Validator
}

// Cmd: shell text that runs op with the host's privilege mode. shellArgs: the arguments are appended by the calling
// shell script (e.g. "$u" in a loop) and are not given here.
func Cmd(mode, op string, shellArgs bool, args ...string) (string, error) {
	o, ok := Ops[op]
	if !ok {
		return "", fmt.Errorf("unknown privileged op %q", op)
	}
	if !shellArgs && len(args) != len(o.Args) {
		return "", fmt.Errorf("%s: expected %d args", op, len(o.Args))
	}
	q := make([]string, len(args))
	for i, a := range args {
		q[i] = Quote(a)
	}
	if mode == "helper" {
		return strings.Join(append([]string{"sudo -n", HelperPath, op}, q...), " "), nil
	}
	inner := "sh -c " + Quote(o.Snippet) + " kanareika " + strings.Join(q, " ")
	if mode == "sudo" {
		return "sudo -n " + inner, nil
	}
	return inner, nil
}

// RenderHelper: the root-owned script installed on servers. Read-only operations, strict argument checks.
func RenderHelper(version string) string {
	lines := []string{
		"#!/bin/sh",
		fmt.Sprintf("# kanareika-collect %s — GENERATED by `kanareika helper`, do not edit by hand.", version),
		"# Read-only data collection for the Kanareika security audit. Allowed in sudoers as the only command",
		"# for the audit user. Each operation takes a fixed number of arguments, each one validated.",
		"set -u",
		"export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
		"umask 077",
		`die() { echo "kanareika-collect: $*" >&2; exit 64; }`,
		`op="${1:-}"; [ $# -gt 0 ] && shift`,
		`case "$op" in`,
	}
	for _, name := range OpOrder {
		o := Ops[name]
		checks := []string{fmt.Sprintf("[ $# -eq %d ] || die 'bad args'", len(o.Args))}
		for i, v := range o.Args {
			n := i + 1
			if v.Kind == "re" {
				checks = append(checks, fmt.Sprintf(`printf '%%s' "$%d" | grep -Eqx %s || die 'bad arg %d'`, n, Quote(v.Rule), n))
			} else {
				alts := make([]string, len(v.Enum))
				for j, e := range v.Enum {
					alts[j] = Quote(e)
				}
				checks = append(checks, fmt.Sprintf(`case "$%d" in %s) ;; *) die 'bad arg %d' ;; esac`, n, strings.Join(alts, "|"), n))
			}
		}
		lines = append(lines, "  "+name+")")
		for _, c := range checks {
			lines = append(lines, "    "+c)
		}
		lines = append(lines, "    "+o.Snippet, "    ;;")
	}
	lines = append(lines, "  version) echo "+Quote(version)+" ;;", `  *) die "unknown operation '$op'" ;;`, "esac")
	return strings.Join(lines, "\n") + "\n"
}

var safe = regexp.MustCompile(`^[\w@%+=:,./-]+$`)

// Quote for sh, exactly as Python's shlex.quote.
func Quote(s string) string {
	if s == "" {
		return "''"
	}
	if safe.MatchString(s) { // RE2's \w is ASCII-only, so a match is already plain ASCII
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'"'"'`) + "'"
}

// Render replaces @P:op@ placeholders in a script with the host-specific privileged command. Ops that take
// arguments expect them from the script (shell variables) right after the placeholder.
func Render(script, mode string) string {
	return placeholder.ReplaceAllStringFunc(script, func(m string) string {
		op := m[3 : len(m)-1]
		c, err := Cmd(mode, op, len(Ops[op].Args) > 0)
		if err != nil {
			return m
		}
		return c
	})
}

var placeholder = regexp.MustCompile(`@P:([a-z-]+)@`)
